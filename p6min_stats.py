r"""P6*: an optimal enforceable E is generated by Psi together with its COMPLIANT minimal weakenings only,
where a minimal FD X'->A of E outside D_a is compliant iff X' lies inside Y+_Psi for some minimal FD Y->B of Psi^+
that is critical for Psi^+ (any criticality of X'->A in E is allowed).
Aggregates per instance with lambda > 0 and no plain optimum:
  any_E : some optimal E satisfies P6*;   min_E : every inclusion-minimal optimal E satisfies P6*;   all_E : every optimal E.
"""
import sys, time, random
from weak_stats import optimal_sets, random_instance
from minloss_bruteforce import *

def main(n, seconds, cap, seed):
    rng = random.Random(seed)
    names = [chr(ord('a') + i) for i in range(n)]
    t0 = time.time(); seen = set()
    stats = {'instances': 0, 'nonplain': 0, 'any_E_fail': 0, 'min_E_fail': 0, 'all_E_fail': 0, 'sum_Wall': 0, 'sum_Wc': 0, 'minE_noncompliant': 0, 'minE_count': 0}
    while time.time() - t0 < seconds:
        D = random_instance(n, rng)
        cltD = closure_table(D, n)
        if cltD[0] != 0:
            continue
        sig = tuple(cltD)
        if sig in seen:
            continue
        seen.add(sig)
        r = optimal_sets(n, D, cap=cap)
        if r is None:
            continue
        lam, Da, hits = r
        stats['instances'] += 1
        if lam == 0:
            continue
        byE = {}
        for Delta, clt in hits:
            byE[tuple(clt)] = (Delta, clt)
        if any(not [f for f in atomic_cover(clt, n) if f not in Da] for (_, clt) in byE.values()):
            continue
        stats['nonplain'] += 1
        ok = {}; allc = {}
        for key, (Delta, clt) in byE.items():
            Psi = [f for f in Da if f not in Delta]
            cltPsi = closure_table(Psi, n)
            PsiA = atomic_cover(cltPsi, n)
            crit = [Y for (Y, B) in PsiA if not is_bcnf_schema(Y | B, cltPsi)]
            Ea = atomic_cover(clt, n)
            W_all = [f for f in Ea if f not in Da]
            W_c = [f for f in W_all if any((f[0] & ~cltPsi[Y]) == 0 for Y in crit)]
            stats['sum_Wall'] += len(W_all); stats['sum_Wc'] += len(W_c)
            ok[key] = closure_table(Psi + W_c, n) == list(clt)
            allc[key] = (len(W_c) == len(W_all))
        keys = list(byE.keys())
        def inside(c1, c2):
            return all((c1[X] & ~c2[X]) == 0 for X in range(1 << n))
        minimal = [k for k in keys if not any(k2 != k and inside(k2, k) for k2 in keys)]
        any_E = any(ok.values()); all_E = all(ok.values()); min_E = all(ok[k] for k in minimal)
        stats['minE_count'] += len(minimal); bad = [k for k in minimal if not allc[k]]; stats['minE_noncompliant'] += len(bad)
        if bad and stats['minE_noncompliant'] <= 3:
            Delta, clt = byE[bad[0]]; Ea = atomic_cover(clt, n)
            print(f"NONCOMPLIANT minimal E: lambda={lam} D={[fmt_fd(f, names) for f in D]} Delta={[fmt_fd(f, names) for f in Delta]} E_a={[fmt_fd(f, names) for f in Ea]}", flush=True)
        for name, v in [('any_E', any_E), ('min_E', min_E), ('all_E', all_E)]:
            if not v:
                stats[name + '_fail'] += 1
                if name != 'all_E':
                    print(f"FAIL {name}: lambda={lam} D={[fmt_fd(f, names) for f in D]}", flush=True)
        if stats['instances'] % 5000 == 0:
            print(f"  ... {time.time()-t0:.0f}s {stats}", flush=True)
    print("DONE", stats, f"{time.time()-t0:.0f}s", flush=True)

if __name__ == "__main__":
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 5
    seconds = int(sys.argv[2]) if len(sys.argv) > 2 else 120
    cap = int(sys.argv[3]) if len(sys.argv) > 3 else 200000
    seed = int(sys.argv[4]) if len(sys.argv) > 4 else 41
    main(n, seconds, cap, seed)
