# Structured search over the sets Delta (the default implementation of line 2-3 of Alg. 1)
#
# Every closed choice Delta that satisfies the cover condition of Lem. 5.3 (a *candidate*) is reached by a
# depth-first search that grows Delta one minimal FD at a time, with iterative deepening on the weight bound.
# At a node Delta the search computes *requirement sets*, sets of minimal FDs of which every candidate above
# Delta contains at least one:
#   - for every f in Delta that Sigma_a - Delta still implies, the FDs that fired in the closure computation of
#     lhs(f) without Delta (a closed superset of Delta must break every such derivation);
#   - for every critical minimal FD g = Y -> B outside Delta that U cup C(Delta) cup Delta does not imply, the
#     critical minimal FDs h with lhs(h) inside Y+ together with the violators of their schemata (a new
#     derivation of g needs a new critical FD h with lhs(h) inside Y+ in Delta, or in C(Delta) through a new
#     violator of its schema in Delta; uncritical FDs are in U already).
# The search branches over the smallest requirement set, and pairwise disjoint requirement sets give a lower
# bound on the weight still to be added (a packing bound) that prunes the node. A node without requirement
# sets is a candidate: at the current bound its feasibility is decided by the search over weakened FDs
# (search_W); below the bound the search extends it by an arbitrary FD, so that every heavier candidate is
# reached as well. The first feasible candidate is optimal because the bounds increase.
# ---------------------------------------------------------------------------------------------------------------

STRICT_COVER = True
BUDGET_LIMIT = 60   # the number of weight bounds of the iterative deepening under non-unit weights

def _subset_sums(weights, cap, limit=None, max_sums=100000):
    """(budgets, rest): the distinct subset sums of the weights up to `cap` in increasing order (unit weights:
    0..m), at most `limit` of them unless the weights are unit, and rest = None if the budgets contain every subset
    sum, else a lower bound on the smallest subset sum above the last budget. Above max_sums sums, only the
    smallest are kept; the list stays complete up to its largest element, since every subset whose sum does not
    exceed it has all its partial sums below it."""
    limit = BUDGET_LIMIT if limit is None else limit
    if all(x == 1 for x in weights):
        m = len(weights)
        top = m if cap is None else max(-1, min(m, int(cap)))
        return list(range(0, top + 1)), (None if top >= m else top + 1)
    top = cap
    sums = {0}
    for x in weights:
        sums |= {s + x for s in sums if top is None or s + x <= top}
        if len(sums) > max_sums:
            sums = set(sorted(sums)[:max_sums])
            top = max(sums)
    budgets = sorted(sums)
    if len(budgets) > limit:
        return budgets[:limit], budgets[limit]
    if top is None or sum(weights) <= top:
        return budgets, None
    # the smallest subset sum above top is s + x for a subset sum s <= top of the other weights, so the smallest
    # s + x > top over all budgets s and weights x bounds it from below
    rest = min(budgets[i] + x for x in set(weights)
               for i in [bisect.bisect_right(budgets, top - x)] if i < len(budgets))
    return budgets, rest

def _structured(n, Da, w, R, deadline, max_w, max_extra, max_weight, stats, verbose=False):
    """the tree search described above; returns (best, incomplete_at) with best = (weight, Delta, W, E, Ea, U)
    or None, and incomplete_at the smallest weight at which a candidate was not fully processed (inf if none)"""
    fds = list(Da.fds)
    idx = {f: i for i, f in enumerate(fds)}
    unc, crit = split_critical(Da)
    crit_viol = [(f, violators(Da, f[0] | (1 << f[1]))) for f in crit]
    viol_of = dict(crit_viol)
    act = {}
    for g in crit:
        Yc = Da.closure(g[0])
        s = set()
        for h in crit:
            if h[0] & ~Yc == 0:
                s.add(h)
                s.update(viol_of[h])
        act[g] = s
    inf = float("inf")
    state = {"best": None, "incomplete_at": inf, "timeout": False}
    for k in ("nodes", "candidates", "pruned", "extension"):
        stats.setdefault(k, 0)
    stats.setdefault("tested", 0)

    def unsatisfied(Delta):
        # a critical minimal FD of Sigma is uncritical for the enforced FDs only if every violator of its schema
        # is unenforced (the proof of the cover condition), so it joins the cover only when all its violators
        # are in Delta; STRICT_COVER = False keeps the weaker condition (some violator in Delta)
        C = [f for (f, viol) in crit_viol if (all if STRICT_COVER else any)(v in Delta for v in viol)]
        F = FDSet(n, unc + C + list(Delta))
        return [g for g in crit if g not in Delta and not F.implies(g[0], g[1])]

    def requirements(Delta):
        reqs = []
        dis = set(idx[f] for f in Delta)
        for f in Delta:
            rec = []
            if (Da.closure_without(f[0], dis, rec) >> f[1]) & 1:
                reqs.append(frozenset(fds[i] for i in rec))
        for g in unsatisfied(Delta):
            reqs.append(frozenset(act[g] - Delta))
        return reqs

    def packing(reqs):
        # the lighter of two valid bounds: the greedy packing of pairwise disjoint requirement sets, and the
        # fractional packing by dual ascent on the hitting-set relaxation (every requirement set raises its dual
        # value up to the smallest remaining slack of its elements); both are feasible duals, so the larger wins
        used = set()
        total = 0
        load = {}
        frac = 0.0
        for r in sorted(reqs, key=len):
            if not (r & used):
                used |= r
                total += min(_weight(w, h) for h in r)
            slack = min(_weight(w, h) - load.get(h, 0.0) for h in r)
            if slack > 1e-9:
                frac += slack
                for h in r:
                    load[h] = load.get(h, 0.0) + slack
        return max(total, frac - 1e-9)

    def dfs(Delta, wt, bound, seen):
        if state["best"] is not None or state["timeout"]:
            return
        if deadline is not None and time.time() > deadline:
            state["timeout"] = True
            state["incomplete_at"] = min(state["incomplete_at"], bound)
            return
        if Delta in seen:
            return
        seen.add(Delta)
        stats["nodes"] += 1
        reqs = requirements(Delta)
        if reqs:
            if any(len(r) == 0 for r in reqs) or wt + packing(reqs) > bound:
                stats["pruned"] += 1
                return
            r = min(reqs, key=len)
            for h in sorted(r, key=lambda h: (_weight(w, h), idx[h])):
                wt2 = wt + _weight(w, h)
                if wt2 <= bound:
                    dfs(Delta | {h}, wt2, bound, seen)
                    if state["best"] is not None or state["timeout"]:
                        return
            return
        if wt == bound:
            stats["candidates"] += 1
            Psi = FDSet(n, [f for f in fds if f not in Delta])
            stats["tested"] += 1
            try:
                Pa = atomic_cover(Psi, deadline=deadline)
            except DeadlineExceeded:
                state["timeout"] = True
                state["incomplete_at"] = min(state["incomplete_at"], bound)
                return
            ok, U = enforceable(Pa)
            if ok:
                state["best"] = (wt, Delta, [], Psi, Pa, U)
                return
            if Delta:
                r, cut, timed_out = search_W(n, R, Psi, Pa, sorted(Delta), max_w, deadline, stats, max_extra)
                if timed_out:
                    state["timeout"] = True
                if cut and r is None:
                    state["incomplete_at"] = min(state["incomplete_at"], wt)
                if r is not None:
                    W, E, Ea, U = r
                    state["best"] = (wt, Delta, W, E, Ea, U)
            return
        stats["extension"] += 1
        for h in fds:
            if h in Delta:
                continue
            wt2 = wt + _weight(w, h)
            if wt2 <= bound:
                dfs(Delta | {h}, wt2, bound, seen)
                if state["best"] is not None or state["timeout"]:
                    return

    weights = sorted(_weight(w, f) for f in fds)
    budgets, rest = _subset_sums(weights, max_weight)
    for b in budgets:
        t = time.time()
        n0 = stats["nodes"]
        dfs(frozenset(), 0, b, set())
        if verbose:
            print("  bound %s: %d nodes, %.1fs%s" % (b, stats["nodes"] - n0, time.time() - t,
                                                   ", solved" if state["best"] is not None else (", timeout" if state["timeout"] else "")), flush=True)
        if state["best"] is not None or state["timeout"]:
            break
    else:
        if rest is not None:
            # every examined budget failed, and the budgets from `rest` on were not examined
            state["incomplete_at"] = min(state["incomplete_at"], rest)
    return state["best"], state["incomplete_at"]

def drop(n, Da, w=None, R=None, time_limit=None, max_w=4, max_extra=None, max_delta=None, max_weight=None,
         heuristic=True, verbose=False, method="structured", ascend_time=None):
    """Drop(R, Sigma, w) with Sigma given by its atomic cover Da (an FDSet) over the universe R.
    w maps minimal FDs (X, A) to positive weights (default 1). max_w bounds |W|, max_extra the number of
    attributes a weakened FD may add to a left-hand side (None: unbounded), max_weight the weight of the sets
    Delta that are examined (None: unbounded). method "structured" (default) runs the tree search over the
    sets Delta, method "plain" lists the closed choices by increasing weight (max_delta bounds their size).
    When the budget is exhausted, the heuristic returns the lightest of the uncritical fixpoint, the greedy and,
    with ascend_time > 0, the ascent (Algorithm "Ascend") from each of these two states within ascend_time.
    Returns a DropResult; res.exact tells whether the loss is proved minimal, res.lower_bound is certified."""
    if method == "plain":
        return drop_plain(n, Da, w, R, time_limit, max_w, max_extra, max_delta, heuristic, verbose)
    t0 = time.time()
    # on large schemata the exact search gets half of the budget and the greedy the rest (up to 1.5 budgets)
    large = len(Da) > 200
    deadline = None if time_limit is None else t0 + (time_limit / 2 if large and heuristic else time_limit)
    R = (1 << n) - 1 if R is None else R
    stats = {"nodes": 0, "candidates": 0, "pruned": 0, "extension": 0, "tested": 0, "incomplete": False}
    res = DropResult(stats=stats)
    best, incomplete_at = _structured(n, Da, w, R, deadline, max_w, max_extra, max_weight, stats, verbose)
    inf = float("inf")
    stats["time"] = time.time() - t0
    stats["incomplete"] = incomplete_at < inf
    if best is not None:
        wt, Delta, W, E, Ea, U = best
        res.loss = wt
        res.delta = sorted(Delta)
        res.W = list(W)
        res.E, res.Ea = E, Ea
        res.design = design_from_cover(Ea, U, R)
        res.exact = incomplete_at >= wt
        res.lower_bound = wt if res.exact else incomplete_at
        return res
    res.lower_bound = incomplete_at if incomplete_at < inf else 0
    if heuristic:
        # the uncritical fixpoint first (cheap), then the greedy with the remaining budget; the lighter wins
        hdeadline = (time.time() + 30) if time_limit is None else max(time.time() + 30, t0 + 1.5 * time_limit)
        cands = []
        fx = uncritical_fixpoint(n, Da, w, R, hdeadline, stats)
        if fx is not None:
            cands.append(fx)
        g = greedy_restarts(n, Da, w, R, hdeadline, stats)
        if g is not None:
            cands.append(g)
        labels = {id(fx): "fixpoint", id(g): "greedy"}
        if cands:
            cands.sort(key=lambda c: sum(_weight(w, f) for f in c[0]))
            Delta, Psi, Pa, U = cands[0]
            stats["heuristic_source"] = labels[id(cands[0])]
            res.heuristic = True
            res.loss = sum(_weight(w, f) for f in Delta)
            res.delta = sorted(Delta)
            res.W = []
            res.E, res.Ea = Psi, Pa
            res.design = design_from_cover(Pa, U, R)
            if ascend_time:
                # the ascent (Algorithm "Ascend") from the uncritical minimal FDs of each candidate, lightest first,
                # with an equal share of ascend_time each; the lightest result wins
                t3 = time.time()
                share = ascend_time / len(cands)
                stats["ascend_candidates"] = [(labels[id(c)], sum(_weight(w, f) for f in c[0])) for c in cands]
                for c in cands:
                    astats = {}
                    a = ascend(n, Da, w, R, time.time() + share, astats, start=list(c[3].fds))
                    if a is None:
                        continue
                    design_a, loss_a, Delta_a, psi_a = a
                    stats["ascend_candidates"].append(("ascend-" + labels[id(c)], loss_a))
                    if labels[id(c)] == stats["heuristic_source"] or "ascend_moves_tried" not in stats:
                        stats.update({k: v for k, v in astats.items()})
                    if (loss_a, len(design_a)) < (res.loss, len(res.design)):   # fewer schemata on ties
                        res.loss = loss_a
                        res.delta = sorted(Delta_a)
                        res.E = FDSet(n, psi_a)
                        res.Ea = atomic_cover(res.E)
                        res.design = design_a
                        stats["heuristic_source"] = "ascend-" + labels[id(c)]
                stats["time_ascend"] = time.time() - t3
    stats["time"] = time.time() - t0
    return res

def drop_from_fds(n, F, w=None, **kw):
    return drop(n, atomic_cover(F), w, **kw)

