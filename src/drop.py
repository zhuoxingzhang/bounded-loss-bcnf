r"""drop.py: the exact algorithm Drop(R, Sigma, w) of the paper (Alg. 1), on top of fdlib.

Drop enumerates the sets Delta of minimal FDs to leave unenforced in increasing order of weight, skips the
sets that are not closed choices (some element implied by the rest) and the sets that fail the cover
condition of Lemma 5.3, and for each remaining Delta searches a set W of weakened FDs such that
E = (Psi cup W)^+ with Psi = Sigma_a - Delta avoids Delta and is enforceable (Theorem 3.18). The search
over W is an iterative-deepening search over candidate weakened FDs with the monotone pruning "E already
implies an element of Delta"; local weakened FDs are tried first.

The result is exact when the enumeration completed within the bounds (max_delta elements of Delta, max_w
weakened FDs, candidate cap, time limit). When it did not, the result carries a certified lower bound
(every set Delta of smaller weight was examined) and, if no design was found at all, a design computed by
a greedy heuristic over plain designs (upper bound). The universe R may be a proper subset of 0..n-1.

The sets Delta are generated by the structured tree search described before _structured() below;
drop_plain() keeps the plain enumeration by increasing weight for cross-checks.
"""
import time
import bisect
from itertools import combinations
from fdlib import *
from ascend import ascend

class DropResult:
    def __init__(self, **kw):
        self.design = None      # list of (S, keys)
        self.loss = None        # loss of the returned design
        self.delta = None       # minimal FDs left unenforced
        self.W = None           # weakened FDs that generate E together with Psi
        self.E = None           # FDSet cover of the enforced FDs
        self.Ea = None          # atomic cover of E
        self.exact = False      # enumeration complete within the bounds: loss == lambda
        self.lower_bound = 0    # every closed Delta of weight < lower_bound is infeasible
        self.heuristic = False  # the design comes from the greedy heuristic
        self.stats = {}
        self.__dict__.update(kw)

    def __repr__(self):
        return "DropResult(loss=%s, lb=%s, |delta|=%s, |W|=%s, exact=%s, heuristic=%s, %s)" % (
            self.loss, self.lower_bound, None if self.delta is None else len(self.delta),
            None if self.W is None else len(self.W), self.exact, self.heuristic, self.stats)

def _weight(w, f):
    return 1 if w is None else w.get(f, 1)

def cover_condition(n, Da, unc, crit_viol, Delta):
    """Lemma 5.3: U cup C(Delta) cup Delta must cover Sigma."""
    Dset = set(Delta)
    C = [f for (f, viol) in crit_viol if any(v in Dset for v in viol)]
    F = FDSet(n, unc + C + list(Delta))
    return all(F.implies(X, A) for (X, A) in Da.fds)

def weakenings(R, f, Psi, Delta):
    """Candidate weakened FDs X' -> A of f = (X, A): X < X' <= R - A, A not implied by Psi from X',
    and Psi + X' -> A does not imply an element of Delta."""
    X, A = f
    free_bits = list(bits(R & ~X & ~(1 << A)))
    out = []
    for k in range(1, len(free_bits) + 1):
        for sub in combinations(free_bits, k):
            Xp = X | mask(sub)
            if Psi.implies(Xp, A):
                continue
            F = FDSet(Psi.n, Psi.fds + [(Xp, A)])
            if any(F.implies(Y, B) for (Y, B) in Delta):
                continue
            out.append((Xp, A))
    return out

def local_candidates(Ea, Delta, Yc, max_extra):
    """Weakened FDs X' -> A of the elements (X, A) of Delta with X < X' <= Yc - A that are not in E yet,
    by increasing size; at most max_extra attributes are added to X (the caller records the cut)."""
    out, cut = [], False
    for (X, A) in Delta:
        if X & ~Yc:
            continue
        free_bits = list(bits(Yc & ~X & ~(1 << A)))
        top = len(free_bits)
        if max_extra is not None and top > max_extra:
            top = max_extra
            cut = True
        for k in range(1, top + 1):
            for sub in combinations(free_bits, k):
                Xp = X | mask(sub)
                if not Ea.implies(Xp, A):
                    out.append((Xp, A))
    return out, cut

def search_W(n, R, Psi, Pa, Delta, w_bound, deadline, stats, max_extra=None):
    """Goal-directed search for a set W of weakened FDs such that E = (Psi cup W)^+ avoids Delta and is
    enforceable. At every node some critical minimal FD g = Y -> B of E that the uncritical ones do not imply
    is chosen, and the search branches over the weakened FDs with left-hand side inside the closure of Y
    for E: every resolution of g in a larger closed set must add such an FD, so the search is complete.
    Returns ((W, E, Ea, U) or None, cut, timed_out) where cut says that a bound (w_bound, max_extra, deadline) was
    hit, so that failure does not certify that Delta is infeasible; an atomic cover past the deadline is a timeout."""
    try:
        return _search_W(n, R, Psi, Pa, Delta, w_bound, deadline, stats, max_extra)
    except DeadlineExceeded:
        return None, True, True

def _search_W(n, R, Psi, Pa, Delta, w_bound, deadline, stats, max_extra):
    base = Psi.fds
    state = {"cut": False, "cut_depth": False, "timeout": False}

    def analyse(Ea):
        unc, crit = split_critical(Ea)
        U = FDSet(n, unc)
        return U, [g for g in crit if not U.implies(g[0], g[1])]

    def options(Ea, obstructions):
        """candidates for the obstruction with the fewest of them (None: a bound cut the candidate list)"""
        best = None
        for g in obstructions:
            cands, cut = local_candidates(Ea, Delta, Ea.closure(g[0]), max_extra)
            if best is None or len(cands) < len(best[0]):
                best = (cands, cut)
                if not cands:
                    break
        cands, cut = best
        if cut:
            state["cut"] = True
        cands.sort(key=lambda h: popcount(h[0]))
        return cands

    def extend(W, h):
        E2 = FDSet(n, base + W + [h])
        if any(E2.implies(Y, B) for (Y, B) in Delta):
            return None
        stats["tested"] += 1
        return E2, atomic_cover(E2, deadline=deadline)

    # greedy descent first: take the candidate that leaves the fewest obstructions
    W, E, Ea = [], Psi, Pa
    U, obstructions = analyse(Ea)
    for depth in range(w_bound):
        if not obstructions:
            return (W, E, Ea, U), state["cut"], False
        best = None
        for h in options(Ea, obstructions):
            r = extend(W, h)
            if r is None:
                continue
            U2, obs2 = analyse(r[1])
            key = (len(obs2), popcount(h[0]))
            if best is None or key < best[0]:
                best = (key, h, r, U2, obs2)
                if not obs2:
                    break
        if best is None:
            break
        _, h, (E, Ea), U, obstructions = best
        W = W + [h]
    if not obstructions:
        return (W, E, Ea, U), state["cut"], False

    # complete search with iterative deepening, states identified by their closed FD set
    def node(W, E, Ea, obstructions, depth, limit, seen):
        if depth >= limit:
            state["cut_depth"] = True
            return None
        if deadline is not None and time.time() > deadline:
            state["cut"] = state["timeout"] = True
            return None
        for h in options(Ea, obstructions):
            r = extend(W, h)
            if r is None:
                continue
            E2, Ea2 = r
            key = frozenset(Ea2.fds)
            if key in seen:
                continue
            seen.add(key)
            U2, obs2 = analyse(Ea2)
            if not obs2:
                return W + [h], E2, Ea2, U2
            r2 = node(W + [h], E2, Ea2, obs2, depth + 1, limit, seen)
            if r2 is not None:
                return r2
            if state["timeout"]:
                return None
        return None

    U0, obs0 = analyse(Pa)
    for limit in range(1, w_bound + 1):
        state["cut_depth"] = False
        r = node([], Psi, Pa, obs0, 0, limit, set())
        if r is not None:
            return r, False, False
        if state["timeout"]:
            return None, True, True
        if not state["cut_depth"]:
            # exhausted without hitting the depth bound: Delta is infeasible (unless candidates were cut)
            return None, state["cut"], False
    return None, True, False

def greedy_plain(n, Da, w, R, deadline, stats, rng=None, top=3, max_options=6):
    """A plain BCNF design by greedy repair: while the uncritical minimal FDs of Psi^+ do not imply some
    critical one g, drop g or one of the violators of its schema (the cheapest option measured by the
    weight added to Delta and the obstructions that remain), keeping Delta a closed choice.
    With rng, the obstruction and the option are chosen at random among the best `top` ones.
    At most `max_options` options are evaluated per step (g and the lightest violators). None at the deadline,
    also when an atomic cover runs past it."""
    try:
        return _greedy_plain(n, Da, w, R, deadline, stats, rng, top, max_options)
    except DeadlineExceeded:
        return None

def _greedy_plain(n, Da, w, R, deadline, stats, rng, top, max_options):
    fds = list(Da.fds)
    idx = {f: i for i, f in enumerate(fds)}
    def close_choice(Delta):
        """Enlarge Delta until no element of Delta is implied by Sigma_a - Delta (cheapest derivations broken)."""
        Delta = set(Delta)
        while True:
            dis = set(idx[f] for f in Delta)
            bad = None
            for f in Delta:
                rec = []
                if (Da.closure_without(f[0], dis, rec) >> f[1]) & 1:
                    bad = (f, rec)
                    break
            if bad is None:
                return Delta
            f, rec = bad
            # among the FDs that fired, drop the cheapest one whose removal breaks the derivation
            best = None
            for i in rec:
                if (Da.closure_without(f[0], dis | {i}) >> f[1]) & 1 == 0:
                    c = _weight(w, fds[i])
                    if best is None or c < best[0]:
                        best = (c, i)
            if best is None:
                best = (min(_weight(w, fds[i]) for i in rec), min(rec, key=lambda i: _weight(w, fds[i])))
            Delta.add(fds[best[1]])
    def evaluate(Delta):
        Psi = FDSet(n, [f for f in fds if f not in Delta])
        Pa = atomic_cover(Psi, deadline=deadline)
        unc, crit = split_critical(Pa)
        U = FDSet(n, unc)
        obstructions = [g for g in crit if not U.implies(g[0], g[1])]
        return Psi, Pa, U, obstructions
    Delta = set()
    while True:
        if deadline is not None and time.time() > deadline:
            return None
        Psi, Pa, U, obstructions = evaluate(Delta)
        if not obstructions:
            return Delta, Psi, Pa, U
        g = obstructions[0] if rng is None else rng.choice(obstructions[:top])
        options = [g] + [v for v in violators(Pa, g[0] | (1 << g[1])) if v != g]
        if len(options) > max_options:
            # every option costs an evaluation (an atomic cover): keep g and the lightest violators
            options = options[:1] + sorted(options[1:], key=lambda h: (_weight(w, h), idx.get(h, len(fds))))[:max_options - 1]
        scored = []
        for h in options:
            if h in Da.fds:
                D2 = close_choice(Delta | {h})
            else:
                # h is a minimal FD of Psi^+ outside Sigma_a: break its cheapest derivation
                dis = set(idx[f] for f in Delta)
                rec = []
                Da.closure_without(h[0], dis, rec)
                cand = [i for i in rec if (Da.closure_without(h[0], dis | {i}) >> h[1]) & 1 == 0] or rec
                if not cand:
                    continue
                i = min(cand, key=lambda i: _weight(w, fds[i]))
                D2 = close_choice(Delta | {fds[i]})
            wt = sum(_weight(w, f) for f in D2)
            _, _, _, obs2 = evaluate(D2)
            key = (len(obs2) == 0 and 0 or 1, wt, len(obs2))
            scored.append((key, D2))
        if not scored:
            return None
        scored.sort(key=lambda t: t[0])
        pick = 0 if rng is None or scored[0][0][0] == 0 else rng.randrange(min(top, len(scored)))
        Delta = scored[pick][1]
        stats["greedy_steps"] = stats.get("greedy_steps", 0) + 1

def greedy_restarts(n, Da, w, R, deadline, stats, restarts=20, seed=0):
    """The deterministic greedy first, then randomised runs until the deadline; the lightest result wins."""
    import random
    best = greedy_plain(n, Da, w, R, deadline, stats)
    rng = random.Random(seed)
    for i in range(restarts):
        if deadline is not None and time.time() > deadline:
            break
        r = greedy_plain(n, Da, w, R, deadline, stats, rng=rng)
        if r is not None and (best is None or sum(_weight(w, f) for f in r[0]) < sum(_weight(w, f) for f in best[0])):
            best = r
            stats["greedy_improved"] = stats.get("greedy_improved", 0) + 1
    return best

def uncritical_fixpoint(n, Da, w, R, deadline, stats):
    """The mass version of the greedy for large schemata: drop every obstruction at once and repeat,
    E_0 = Sigma^+ and E_{i+1} = (uncritical minimal FDs of E_i)^+, until E_i is enforceable (Theorem 3.18).
    Every round costs one atomic cover; the sequence decreases and stops at an enforceable subset of Sigma^+.
    Returns (Delta, Psi, Pa, U) like greedy_plain (Pa the atomic cover of the enforced set, U its uncritical
    minimal FDs, Delta the minimal FDs of Sigma it does not imply), or None at the deadline, also when an atomic
    cover runs past it."""
    Pa = Da
    rounds = 0
    while True:
        if deadline is not None and time.time() > deadline:
            return None
        unc, crit = split_critical(Pa)
        U = FDSet(n, unc)
        if all(U.implies(g[0], g[1]) for g in crit):
            stats["fixpoint_rounds"] = rounds
            Delta = set(f for f in Da.fds if not Pa.implies(f[0], f[1]))
            Psi = FDSet(n, [f for f in Da.fds if f not in Delta])
            return Delta, Psi, Pa, U
        try:
            Pa = atomic_cover(U, deadline=deadline)
        except DeadlineExceeded:
            return None
        rounds += 1

def drop_plain(n, Da, w=None, R=None, time_limit=None, max_w=4, max_extra=None, max_delta=None, heuristic=True, verbose=False):
    """Drop with the plain enumeration of the sets Delta by increasing weight (closed choices only, then the
    cover condition, then search_W); kept for cross-checks, drop() below is the default implementation."""
    t0 = time.time()
    deadline = None if time_limit is None else t0 + time_limit
    R = (1 << n) - 1 if R is None else R
    fds = list(Da.fds)
    idx = {f: i for i, f in enumerate(fds)}
    unc, crit = split_critical(Da)
    crit_viol = [(f, violators(Da, f[0] | (1 << f[1]))) for f in crit]
    # non-redundant minimal FDs are never implied by the rest, whatever else is dropped
    nonred = set(f for i, f in enumerate(fds) if (Da.closure_without(f[0], {i}) >> f[1]) & 1 == 0)
    stats = {"delta_examined": 0, "delta_cover_fail": 0, "delta_not_closed": 0, "tested": 0, "incomplete": False}
    res = DropResult(stats=stats)
    weights = sorted(_weight(w, f) for f in fds)
    inf = float("inf")
    best = None          # (weight, Delta, W, E, Ea, U)
    incomplete_at = inf  # smallest weight of a set Delta that was not fully processed
    examined_upto = inf  # every closed Delta of weight < examined_upto was processed (or beaten)
    m = len(fds)
    stop = False
    k = 0
    while k <= m and not stop:
        lb = sum(weights[:k])  # smallest weight of a set of size k
        if best is not None and lb >= best[0]:
            break
        if max_delta is not None and k > max_delta:
            incomplete_at = min(incomplete_at, lb)
            break
        cands_k = []
        for Delta in combinations(fds, k):
            wt = sum(_weight(w, f) for f in Delta)
            if best is not None and wt >= best[0]:
                continue
            cands_k.append((wt, Delta))
        cands_k.sort(key=lambda t: t[0])
        for wt, Delta in cands_k:
            if best is not None and wt >= best[0]:
                break
            if deadline is not None and time.time() > deadline:
                incomplete_at = min(incomplete_at, wt)
                stop = True
                break
            stats["delta_examined"] += 1
            dis = set(idx[f] for f in Delta)
            if any(f not in nonred and (Da.closure_without(f[0], dis) >> f[1]) & 1 for f in Delta):
                stats["delta_not_closed"] += 1
                continue
            if not cover_condition(n, Da, unc, crit_viol, Delta):
                stats["delta_cover_fail"] += 1
                continue
            Dset = set(Delta)
            Psi = FDSet(n, [f for f in fds if f not in Dset])
            stats["tested"] += 1
            Pa = atomic_cover(Psi)
            ok, U = enforceable(Pa)
            if ok:
                best = (wt, Delta, [], Psi, Pa, U)
                break
            if k == 0:
                continue
            r, cut, timed_out = search_W(n, R, Psi, Pa, Delta, max_w, deadline, stats, max_extra)
            if cut and r is None:
                incomplete_at = min(incomplete_at, wt)
            if timed_out:
                stop = True
            if r is not None:
                W, E, Ea, U = r
                best = (wt, Delta, W, E, Ea, U)
                break
            if stop:
                break
        if stop:
            break
        if best is not None:
            break  # larger sets can only win with a smaller weight, which the lb test above handles
        k += 1
    stats["time"] = time.time() - t0
    stats["incomplete"] = incomplete_at < inf
    if best is not None:
        wt, Delta, W, E, Ea, U = best
        res.loss = wt
        res.delta = list(Delta)
        res.W = list(W)
        res.E, res.Ea = E, Ea
        res.design = design_from_cover(Ea, U, R)
        res.exact = incomplete_at >= wt
        res.lower_bound = wt if res.exact else incomplete_at
        return res
    res.lower_bound = incomplete_at if incomplete_at < inf else 0
    if heuristic:
        g = greedy_restarts(n, Da, w, R, time.time() + (30 if time_limit is None else max(30, time_limit / 2)), stats)
        if g is not None:
            Delta, Psi, Pa, U = g
            res.heuristic = True
            res.loss = sum(_weight(w, f) for f in Delta)
            res.delta = sorted(Delta)
            res.W = []
            res.E, res.Ea = Psi, Pa
            res.design = design_from_cover(Pa, U, R)
    stats["time"] = time.time() - t0
    return res

