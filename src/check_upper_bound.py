"""check_upper_bound.py: random check of the obstruction bound (Theorem "Upper bound" / Lemma "Inheritance").

Claim 1 (inheritance): for closed E with U subseteq E subseteq Sigma^+, where U are the uncritical minimal FDs of
Sigma^+, every element of U is an uncritical minimal FD of E.
Claim 2 (upper bound): U^+ is enforceable, so loss(R, Sigma) <= |Sigma_a - U^+| <= |critical minimal FDs|.

usage: python check_upper_bound.py [n] [seconds] [seed]
"""
import sys, time, random
from fdlib import FDSet, atomic_cover, split_critical, enforceable
from weak_stats import random_instance

def run(n, seconds, seed):
    rng = random.Random(seed)
    t0 = time.time()
    tested = nontrivial = 0
    while time.time() - t0 < seconds:
        D = random_instance(n, rng, mmax=8)
        F = FDSet(n, [(X, A.bit_length() - 1) for (X, A) in D])
        Da = atomic_cover(F)
        unc, crit = split_critical(Da)
        if not crit:
            continue
        tested += 1
        U = FDSet(n, unc)
        Ua = atomic_cover(U)
        ok, _ = enforceable(Ua)
        if not ok:
            print("COUNTEREXAMPLE to claim 2:", n, D)
            return 1
        # inheritance for E = U^+ and for E = (U + random part of the critical FDs)^+
        for trial in range(3):
            part = [f for f in crit if trial == 0 or rng.random() < 0.5] if trial else []
            Ea = atomic_cover(FDSet(n, unc + part))
            unc_E, _ = split_critical(Ea)
            if not set(unc) <= set(unc_E):
                print("COUNTEREXAMPLE to claim 1:", n, D, "E generated by U plus", part)
                return 1
        obstructions = [f for f in crit if not U.implies(f[0], f[1])]
        if obstructions:
            nontrivial += 1
    print("n=%d: %d instances with critical FDs, %d with obstructions, no counterexample in %.0f s" % (n, tested, nontrivial, seconds))
    return 0

if __name__ == "__main__":
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 6
    seconds = float(sys.argv[2]) if len(sys.argv) > 2 else 20
    seed = int(sys.argv[3]) if len(sys.argv) > 3 else 1
    sys.exit(run(n, seconds, seed))
