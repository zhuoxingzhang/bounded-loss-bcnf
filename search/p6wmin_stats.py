r"""Weighted version of the local-weakening conjecture.
With positive weights, every inclusion-minimal feasible dropped set Delta (no proper subset of Delta is feasible)
is the optimal dropped set for suitable weights. So the conjecture for weighted MinLoss needs: for every
inclusion-minimal feasible Delta, some E in F(Psi) is generated by Psi and local weakenings.
Reports failures separately for unit-optimal Delta, inclusion-minimal feasible Delta, and other feasible Delta."""
import sys, time, random
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), os.pardir, "src"))   # the oracle layer minloss_bruteforce.py and weak_stats.py lives in src/
from weak_stats import random_instance
from minloss_bruteforce import *

def main(n, seconds, seed):
    rng = random.Random(seed)
    names = [chr(ord('a') + i) for i in range(n)]
    t0 = time.time(); seen = set()
    stats = {'instances': 0, 'unit_opt': 0, 'incl_min': 0, 'other': 0, 'fail_unit_opt': 0, 'fail_incl_min': 0, 'fail_other': 0, 'plain': 0}
    while time.time() - t0 < seconds:
        D = random_instance(n, rng)
        cltD = closure_table(D, n)
        if cltD[0] != 0:
            continue
        sig = tuple(cltD)
        if sig in seen:
            continue
        seen.add(sig)
        stats['instances'] += 1
        Da = atomic_cover(cltD, n)
        FD = closed_sets(cltD, n)
        byPsi = {}
        for F in coarser_families(FD, n):
            clt = family_to_closure_table(F, n)
            if not realizable(clt, n):
                continue
            Psi = frozenset(f for f in Da if clt[f[0]] & f[1])
            byPsi.setdefault(Psi, []).append(clt)
        if not byPsi:
            continue
        lam = min(len(Da) - len(Psi) for Psi in byPsi)
        for Psi, Es in byPsi.items():
            cltPsi = closure_table(list(Psi), n)
            if any(list(clt) == cltPsi for clt in Es):
                stats['plain'] += 1
                continue
            unit_opt = (len(Da) - len(Psi) == lam)
            incl_min = not any(P2 != Psi and P2 > Psi for P2 in byPsi)  # no feasible Psi' strictly larger
            tag = 'unit_opt' if unit_opt else ('incl_min' if incl_min else 'other')
            stats[tag] += 1
            crit = [Y for (Y, B) in atomic_cover(cltPsi, n) if not is_bcnf_schema(Y | B, cltPsi)]
            ok = False
            for clt in Es:
                Ea = atomic_cover(clt, n)
                W_c = [f for f in Ea if f not in Da and any((f[0] & ~cltPsi[Y]) == 0 for Y in crit)]
                if closure_table(list(Psi) + W_c, n) == list(clt):
                    ok = True; break
            if not ok:
                stats['fail_' + tag] += 1
                if tag != 'other' and stats['fail_' + tag] <= 3:
                    print(f"FAIL {tag}: D={[fmt_fd(f, names) for f in D]} Psi={sorted(fmt_fd(f, names) for f in Psi)} Delta={sorted(fmt_fd(f, names) for f in Da if f not in Psi)} crit={[fmt_set(Y, names) for Y in crit]} |F|={len(Es)} lambda={lam}", flush=True)
        if stats['instances'] % 100 == 0:
            print(f"  ... {time.time()-t0:.0f}s {stats}", flush=True)
    print("DONE", stats, f"{time.time()-t0:.0f}s", flush=True)

if __name__ == "__main__":
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 5
    seconds = int(sys.argv[2]) if len(sys.argv) > 2 else 240
    seed = int(sys.argv[3]) if len(sys.argv) > 3 else 81
    main(n, seconds, seed)
