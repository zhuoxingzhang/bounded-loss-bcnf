"""ascend.py: the ascent from the obstruction design (Algorithm "Ascend" in the paper).

Theorem "Obstruction bound": the closure of the uncritical minimal FDs U of Sigma is enforceable, with loss equal to
the weight of the obstructions O = Sigma_a - U^+. The ascent is a local search over *plain states*: sets Psi of
FDs of Sigma^+ such that every element of Psi is uncritical for Psi^+ (then Psi^+ is enforceable by Theorem
"Enforceable FD sets", statement 3, and the canonical design of Psi^+ has one schema per element of Psi). It starts
from Psi = U, or from the uncritical minimal FDs of any enforceable FD set, and repeats two moves, heaviest
candidate g in Sigma_a - Psi^+ first, until no move improves the loss or the deadline passes:
  add(g):      Psi + g is a plain state;
  swap(g, V):  Psi - V + g is a plain state, where V are the elements of Psi that violate the schema of g, and the
               loss decreases (the minimal FDs of Sigma that g brings in outweigh those that V took along).
Every intermediate state is a valid design, so the search is an anytime algorithm, and the deterministic run is
followed by runs in random candidate order (among candidates of equal weight) until the deadline.

The test "X -> A uncritical for Psi^+", i.e. (XA, Psi^+[XA]) in BCNF, enumerates the subsets Y of XA and asks whether
the closure of Y under Psi meets XA trivially or covers XA (keys skip their supersets): at most 2^|XA| closures of
the generating set, no atomic cover. The test records a witness: the keys of XA it found and the trivial subsets
with (upper bounds of) their closures. After a move only the elements whose schema closure contained the left-hand
side of an added or removed FD can change their status, and their witness settles the recheck with a few closures:
a key stays a key unless a removed FD fired from it, and an added FD Z -> B changes nothing inside XA unless Z lies
in the closure of a trivial subset. An add move is examined entirely through the (cached) closures of the current
state, since the closure of Y under Psi + g is the closure of YB under Psi when Z lies in the latter. The witnesses
are updated in place when a move is accepted. Only the minimal FDs of Sigma whose left-hand side closure contained
a touched left-hand side can change between enforced and unenforced (Lemma "Inheritance" is the special case that
the elements of U never change their status while Psi contains U).
"""
import time, random
from fdlib import FDSet, atomic_cover, design_from_cover, loss_of, popcount, bits, split_critical

def _weight(w, f):
    return 1 if w is None else w[f]

_subsets_cache = {}

def proper_subsets(S):
    """all proper subsets of the attribute set S (bitmask), smallest first, the empty set included"""
    r = _subsets_cache.get(S)
    if r is not None:
        return r
    attrs = list(bits(S))
    out = []
    for mask in range(1 << len(attrs)):
        Y = 0
        for i, a in enumerate(attrs):
            if (mask >> i) & 1:
                Y |= 1 << a
        if Y != S:
            out.append(Y)
    out.sort(key=popcount)
    if len(_subsets_cache) < 50000:
        _subsets_cache[S] = out
    return out

def restrict_to(G, S):
    """the FDs of G whose left-hand side lies in the closure of S: the only FDs that can fire from a subset of S"""
    cS = G.closure(S)
    sub = [f for f in G.fds if f[0] & ~cS == 0]
    return FDSet(G.n, sub) if len(sub) < len(G.fds) else G

def virtual_closure(G, Z, B):
    """the closure function of G + (Z -> B) expressed through the closures of G: the closure of Y under G + g is
    the closure of YB under G if Z lies in the closure of Y under G, and the closure of Y under G otherwise"""
    bit = 1 << B
    def clos(Y):
        c = G.closure(Y)
        if Z & ~c == 0 and not (c >> B) & 1:
            c = G.closure(Y | bit)
        return c
    return clos

def bcnf_witness(G, S, clos=None):
    """(S, E[S]) in BCNF for the closed set E generated by the FDSet G: every subset Y of S whose closure meets S
    non-trivially is a key of S. Subsets are enumerated by size; supersets of a key are keys and are skipped.
    `clos` replaces the closure function of G (virtual_closure for a hypothetical state); by default the closures
    are taken under the restriction of G to the FDs that can fire inside S.
    Returns (ok, keys, trivial) with keys the keys of S found (proper subsets) and trivial the list of (Y, closure)
    for the subsets whose closure meets S trivially; on failure (False, None, None)."""
    if clos is None:
        clos = restrict_to(G, S).closure
    keys, trivial = [], []
    for Y in proper_subsets(S):
        if any(Y & ~K == 0 for K in keys):
            continue
        cl = clos(Y)
        c = cl & S
        if c == Y:
            trivial.append((Y, cl))
        elif c == S:
            keys.append(Y)
        else:
            return False, None, None
    return True, keys, trivial

def uncritical_for(G, S):
    return bcnf_witness(G, S)[0]

def element_violators(clos, psi, S):
    """the elements of psi inside S whose left-hand side is not a key of S under the closure function clos"""
    return [h for h in psi if (h[0] | (1 << h[1])) & ~S == 0 and clos(h[0]) & S != S]

class Ascent:
    def __init__(self, n, Da, w, R, psi, max_schema=14):
        self.n, self.Da, self.w, self.R = n, Da, w, R
        self.max_schema = max_schema
        self.fds = list(Da.fds)
        self.psi = sorted(set(psi))
        self.G = FDSet(n, self.psi)
        self.stats = {"moves_tried": 0, "adds": 0, "swaps": 0, "kicks": 0, "passes": 0, "full_checks": 0, "fast_checks": 0, "dead_keys": 0}
        self.wit = {}
        self.tabu = set()
        self.sc = {}
        self._refresh(None, None)

    def _refresh(self, touched, new_wits):
        """closures of every schema of psi and of every left-hand side of Sigma_a under the current G. A closure
        changes only if it contained a touched left-hand side (the added FD cannot fire otherwise, and no removed
        FD fired), so after a move only those closures are recomputed. The witnesses of the elements whose schema
        closure contained no touched left-hand side stay valid, since no closure inside their schema changed; the
        witnesses of the other elements were updated by the move."""
        G = self.G
        old_sc, old_wit = self.sc, self.wit
        if touched is None:
            self.sc = {h: G.closure(h[0] | (1 << h[1])) for h in self.psi}
            self.lc = {f: G.closure(f[0]) for f in self.fds}
        else:
            old_lc = self.lc
            self.sc = {h: (old_sc[h] if h in old_sc and not any(Z & ~old_sc[h] == 0 for Z in touched)
                           else G.closure(h[0] | (1 << h[1]))) for h in self.psi}
            self.lc = {f: (c if not any(Z & ~c == 0 for Z in touched) else G.closure(f[0]))
                       for f, c in old_lc.items()}
        self.enforced = set(f for f in self.fds if (self.lc[f] >> f[1]) & 1)
        self.wit = {}
        if touched is not None:
            for h in self.psi:
                if h in new_wits:
                    self.wit[h] = new_wits[h]
                elif h in old_wit and h in old_sc and not any(Z & ~old_sc[h] == 0 for Z in touched):
                    self.wit[h] = old_wit[h]

    def plain(self):
        """whether every element is uncritical for psi^+ (computes the witnesses)"""
        return all(self._witness(h) is not None for h in self.psi)

    def _witness(self, h):
        v = self.wit.get(h)
        if v is not None:
            return v
        self.stats["full_checks"] += 1
        ok, keys, trivial = bcnf_witness(self.G, h[0] | (1 << h[1]))
        if not ok:
            return None
        self.wit[h] = (keys, trivial)
        return self.wit[h]

    def _still_uncritical(self, h, clos, G2, add, remove):
        """the witness of h under G2 = G - remove + add, whose closure function is clos (G2 is the FDSet of the
        new state for a swap and None for an add), derived from the witness of h under G; None if h is critical
        for the new state. The closures recorded for trivial subsets that the move cannot touch are kept, so they
        are upper bounds of the closures under G2, which is all the test needs."""
        S = h[0] | (1 << h[1])
        wit = self._witness(h)
        if wit is None:
            return None
        keys, trivial = wit
        Z, bit = add[0], 1 << add[1]
        alive, triv2 = list(keys), []
        if remove:
            # a key of S may stop being a key once the elements of V are gone
            dead, alive = [], []
            for Y in keys:
                full = clos(Y)
                c = full & S
                if c == S:
                    alive.append(Y)
                elif c == Y:
                    dead.append(Y)
                    triv2.append((Y, full))
                else:
                    return None
            if dead:
                # the supersets of a key that became trivial were skipped by the test and need examination,
                # unless they contain a surviving key; the closures are taken under the restriction of G2 to S
                self.stats["dead_keys"] += 1
                clos_S = restrict_to(G2, S).closure
                for Y2 in proper_subsets(S):
                    if any(Y2 & ~K == 0 for K in alive):
                        continue
                    if not any(Y2 != Y and Y2 & ~Y == 0 for Y in dead):
                        continue
                    full = clos_S(Y2)
                    c = full & S
                    if c == S:
                        alive.append(Y2)
                    elif c == Y2:
                        triv2.append((Y2, full))
                    else:
                        return None
        # a trivial subset changes its closure inside S only if the added FD fires from it; under G - V the
        # closure of Y shrinks, so Z inside the recorded closure is necessary for that, and the closure under
        # G + g, which the cache of G knows, bounds the closure under G2 from above
        for Y, cl in trivial:
            if Z & ~cl == 0:
                if remove:
                    bound = self.G.closure(Y | bit)
                    if bound & S == Y:
                        triv2.append((Y, cl & bound))
                        continue
                full = clos(Y)
                c = full & S
                if c == S:
                    alive.append(Y)
                elif c == Y:
                    triv2.append((Y, full))
                else:
                    return None
            else:
                triv2.append((Y, cl))
        self.stats["fast_checks"] += 1
        return alive, triv2

    def loss(self):
        return sum(_weight(self.w, f) for f in self.fds if f not in self.enforced)

    def _try(self, add, remove, clos=None):
        """the state psi - remove + add if it is plain and lighter; returns (gain, psi2, touched, witnesses) or
        None. An add move is examined through the closures of the current G (virtual_closure), a swap through a
        fresh FDSet of the new state."""
        self.stats["moves_tried"] += 1
        psi2 = [h for h in self.psi if h not in remove] + [add]
        G2 = None
        if remove:
            G2 = FDSet(self.n, psi2)
            clos = G2.closure
        elif clos is None:
            clos = virtual_closure(self.G, add[0], add[1])
        touched = [add[0]] + [v[0] for v in remove]
        S = add[0] | (1 << add[1])
        self.stats["full_checks"] += 1
        ok, keys, trivial = bcnf_witness(None, S, clos)
        if not ok:
            return None
        new_wits = {add: (keys, trivial)}
        # elements whose schema closure contained a touched left-hand side may change their status
        for h in self.psi:
            if h in remove:
                continue
            c = self.sc[h]
            if any(Z & ~c == 0 for Z in touched):
                wit = self._still_uncritical(h, clos, G2, add, remove)
                if wit is None:
                    return None
                new_wits[h] = wit
        # the enforced minimal FDs of Sigma change only where a touched left-hand side was in reach
        gain = 0
        for f in self.fds:
            c = self.lc[f]
            if any(Z & ~c == 0 for Z in touched) or f == add:
                now = (clos(f[0]) >> f[1]) & 1 == 1
                was = f in self.enforced
                if now and not was:
                    gain += _weight(self.w, f)
                elif was and not now:
                    gain -= _weight(self.w, f)
        return gain, psi2, touched, new_wits

    def _apply(self, r, kind):
        gain, psi2, touched, new_wits = r
        self.stats[kind] += 1
        self.psi = sorted(psi2)
        self.G = FDSet(self.n, self.psi)
        self._refresh(touched, new_wits)

    def _climb(self, deadline, rng=None):
        """passes over the candidates until no move improves the loss; returns whether the deadline passed"""
        improved = True
        timed_out = False
        while improved and not timed_out:
            improved = False
            self.stats["passes"] += 1
            cands = [f for f in self.fds if f not in self.enforced and f not in self.tabu and popcount(f[0]) + 1 <= self.max_schema]
            if rng is not None:
                rng.shuffle(cands)
            cands.sort(key=lambda f: (-_weight(self.w, f), popcount(f[0])))
            for g in cands:
                if deadline is not None and time.time() > deadline:
                    timed_out = True
                    break
                if g in self.enforced:
                    continue
                S = g[0] | (1 << g[1])
                clos1 = virtual_closure(self.G, g[0], g[1])
                r = self._try(g, (), clos1)
                if r is None:
                    # exchange g for the elements of psi that violate its schema
                    V = element_violators(clos1, self.psi, S)
                    if not V:
                        continue
                    r = self._try(g, V)
                    if r is None or r[0] <= 0:
                        continue
                    self._apply(r, "swaps")
                else:
                    self._apply(r, "adds")
                improved = True
        return timed_out

    def _kick(self, rng, tries=20):
        """a random perturbation that keeps the set uncritical whatever its gain: an exchange of a random
        candidate for the violators of its schema, or, when no such exchange is feasible, the removal of a random
        element together with the elements that turn critical without it. The removed elements are tabu for the
        following climb, so that the climb does not undo the kick at once."""
        if tries and rng.random() < 0.5:
            cands = [f for f in self.fds if f not in self.enforced and popcount(f[0]) + 1 <= self.max_schema]
            rng.shuffle(cands)
            for g in cands[:tries]:
                S = g[0] | (1 << g[1])
                clos1 = virtual_closure(self.G, g[0], g[1])
                V = element_violators(clos1, self.psi, S)
                if not V:
                    continue
                r = self._try(g, V)
                if r is not None:
                    self.tabu = set(V)
                    self._apply(r, "kicks")
                    return True
        if not self.psi:
            return False
        remove = set(rng.sample(self.psi, min(len(self.psi), rng.randint(1, 4))))
        while True:
            psi2 = [x for x in self.psi if x not in remove]
            G2 = FDSet(self.n, psi2)
            touched = [v[0] for v in remove]
            broken, new_wits = [], {}
            for x in psi2:
                if any(Z & ~self.sc[x] == 0 for Z in touched):
                    ok, keys, trivial = bcnf_witness(G2, x[0] | (1 << x[1]))
                    self.stats["full_checks"] += 1
                    if ok:
                        new_wits[x] = (keys, trivial)
                    else:
                        broken.append(x)
            if not broken:
                break
            remove |= set(broken)
        self.tabu = set(remove)
        self.stats["kicks"] += 1
        self.psi, self.G = sorted(psi2), G2
        self._refresh(touched, new_wits)
        return True

    def run(self, deadline, rng=None, max_kicks=0):
        """the climb, followed by up to max_kicks perturbations (iterated local search) until the deadline or
        until max_kicks consecutive kicks fail to improve the best state, which is restored at the end"""
        self.tabu = set()
        timed_out = self._climb(deadline, rng)
        best = (self.loss(), list(self.psi))
        krng = rng if rng is not None else random.Random(0)
        stale = 0
        while max_kicks and not timed_out and stale < max_kicks:
            if not self._kick(krng):
                break
            timed_out = self._climb(deadline, krng)
            self.tabu = set()
            l = self.loss()
            if l < best[0]:
                best, stale = (l, list(self.psi)), 0
            else:
                stale += 1
        if self.loss() > best[0]:
            self.psi = sorted(best[1])
            self.G = FDSet(self.n, self.psi)
            self.wit, self.sc = {}, {}
            self._refresh(None, None)
        self.stats["timed_out"] = timed_out
        return self

    def design(self):
        """the canonical design of psi^+ (Corollary "Canonical designs"), grouped by left-hand side"""
        Ga = atomic_cover(self.G)
        return design_from_cover(Ga, self.G, self.R)

def plain_start(Ea):
    """the uncritical minimal FDs of an enforceable FD set given by its atomic cover: a plain state generating it"""
    unc, crit = split_critical(Ea)
    return unc

def ascend(n, Da, w, R, deadline, stats, start=None, restarts=20, seed=0, max_schema=14, max_kicks=0):
    """Ascent from the obstruction design (start = the uncritical minimal FDs of Sigma) or from any plain state:
    the deterministic run first, then runs in random candidate order until the deadline or `restarts` runs, the
    lightest state wins; with max_kicks > 0 every run continues as an iterated local search (random exchanges
    followed by climbs) until the deadline or until max_kicks consecutive kicks bring no improvement.
    Returns (design, loss, Delta, psi) with Delta the unenforced minimal FDs, or None if the start is not plain."""
    if start is None:
        start = plain_start(Da)
    base = Ascent(n, Da, w, R, start, max_schema)
    if not base.plain():
        return None
    rng = random.Random(seed)
    best = None
    runs = 0
    for i in range(1 + restarts):
        if i > 0 and (deadline is None or time.time() > deadline):
            break
        asc = base if i == 0 else Ascent(n, Da, w, R, start, max_schema)
        asc.run(deadline, None if i == 0 else rng, max_kicks)
        runs += 1
        if best is None or asc.loss() < best.loss():
            best = asc
            stats["ascend_best_run"] = i
        if i == 0:
            stats.update({"ascend_" + k: v for k, v in asc.stats.items()})
    stats["ascend_runs"] = runs
    stats["ascend_loss"] = best.loss()
    t = time.time()
    design = best.design()
    stats["ascend_design_seconds"] = time.time() - t
    loss = loss_of(Da, best.G, w)
    Delta = [f for f in Da.fds if f not in best.enforced]
    return design, loss, Delta, best.psi

