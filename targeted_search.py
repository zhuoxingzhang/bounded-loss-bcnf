r"""Targeted counterexample search for the local-weakening conjecture (unit weights, level-wise exact solver).
Seeds: the non-optimal counterexample {BD->C, AC->E, DE->A} and the failing universal example, embedded in n attributes,
plus 1..k random FDs. Also instances with more FDs than random_instance's default. Reports any optimal instance where NO
optimal E is generated by Psi and local weakenings (any_E failure)."""
import sys, time, random
from weak_stats import optimal_sets
from minloss_bruteforce import *

def m(t): return sum(1 << (ord(c) - 97) for c in t)
BASES = [
    [(m('bd'), m('c')), (m('ac'), m('e')), (m('de'), m('a'))],
    [(m('acd'), m('b')), (m('bc'), m('a')), (m('ce'), m('b')), (m('ac'), m('e')), (m('a'), m('b')), (m('c'), m('d'))],
    [(m('cd'), m('e')), (m('e'), m('c')), (m('a'), m('e')), (m('bd'), m('c')), (m('bc'), m('a'))],
]

def rand_fd(n, rng, maxl=3):
    k = rng.randint(1, maxl)
    X = 0
    while bin(X).count('1') < k:
        X |= 1 << rng.randrange(n)
    A = rng.randrange(n)
    while X & (1 << A):
        A = rng.randrange(n)
    return (X, 1 << A)

def main(n, seconds, cap, seed, extra):
    rng = random.Random(seed)
    names = [chr(ord('a') + i) for i in range(n)]
    t0 = time.time(); seen = set()
    stats = {'instances': 0, 'nontrivial': 0, 'nonplain': 0, 'any_E_fail': 0, 'skipped': 0}
    while time.time() - t0 < seconds:
        if rng.random() < 0.7:
            base = list(rng.choice(BASES))
            # random relabeling of attributes
            perm = list(range(n)); rng.shuffle(perm)
            def remap(S): return sum(1 << perm[i] for i in range(n) if S & (1 << i))
            D = [(remap(X), remap(A)) for (X, A) in base]
            for _ in range(rng.randint(1, extra)):
                D.append(rand_fd(n, rng))
        else:
            D = [rand_fd(n, rng) for _ in range(rng.randint(4, 4 + extra))]
        cltD = closure_table(D, n)
        if cltD[0] != 0:
            continue
        sig = tuple(cltD)
        if sig in seen:
            continue
        seen.add(sig)
        r = optimal_sets(n, D, cap=cap)
        if r is None:
            stats['skipped'] += 1; continue
        lam, Da, hits = r
        stats['instances'] += 1
        if lam == 0:
            continue
        stats['nontrivial'] += 1
        byE = {tuple(clt): (Delta, clt) for Delta, clt in hits}
        if any(not [f for f in atomic_cover(clt, n) if f not in Da] for (_, clt) in byE.values()):
            continue
        stats['nonplain'] += 1
        ok = False
        for Delta, clt in byE.values():
            Psi = [f for f in Da if f not in Delta]
            cltPsi = closure_table(Psi, n)
            crit = [Y for (Y, B) in atomic_cover(cltPsi, n) if not is_bcnf_schema(Y | B, cltPsi)]
            Ea = atomic_cover(clt, n)
            W_c = [f for f in Ea if f not in Da and any((f[0] & ~cltPsi[Y]) == 0 for Y in crit)]
            if closure_table(Psi + W_c, n) == list(clt):
                ok = True; break
        if not ok:
            stats['any_E_fail'] += 1
            print(f"FAIL any_E: lambda={lam} D={[fmt_fd(f, names) for f in D]}", flush=True)
        if stats['instances'] % 1000 == 0:
            print(f"  ... {time.time()-t0:.0f}s {stats}", flush=True)
    print("DONE", stats, f"{time.time()-t0:.0f}s", flush=True)

if __name__ == "__main__":
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 6
    seconds = int(sys.argv[2]) if len(sys.argv) > 2 else 300
    cap = int(sys.argv[3]) if len(sys.argv) > 3 else 300000
    seed = int(sys.argv[4]) if len(sys.argv) > 4 else 101
    extra = int(sys.argv[5]) if len(sys.argv) > 5 else 4
    main(n, seconds, cap, seed, extra)
